"""Copy the current school.db into the PostgreSQL database in DATABASE_URL.

Run once with the database's external connection URL before switching users to
the hosted app. Existing PostgreSQL rows are preserved; duplicate IDs are
skipped. Photos are not stored in SQLite and must be copied separately.
"""
import os
import sqlite3
import sys

import main


def migrate():
    if not main.DATABASE_URL:
        raise SystemExit("Set DATABASE_URL to the PostgreSQL external connection URL first.")
    if not os.path.isfile(main.DB_PATH):
        raise SystemExit(f"SQLite source database not found: {main.DB_PATH}")

    source = sqlite3.connect(main.DB_PATH)
    target = main._connect()
    count = 0
    try:
        schema = main.SCHEMA_SQL.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
        target.executescript(schema)
        table_names = list(main.TABLE_COLUMNS)
        populated = any(target.execute(f'SELECT COUNT(*) FROM "{table}"').fetchone()[0] for table in table_names)
        if populated and "--replace-destination" not in sys.argv:
            raise SystemExit("Target PostgreSQL has data. Re-run with --replace-destination to replace it from school.db.")
        if populated:
            target.execute("TRUNCATE TABLE " + ",".join(f'"{table}"' for table in table_names) + " RESTART IDENTITY CASCADE")
        for table in main.TABLE_COLUMNS:
            source_columns = {row[1] for row in source.execute(f'PRAGMA table_info("{table}")')}
            columns = [name for name in main.TABLE_COLUMNS[table] if name in source_columns]
            if not columns:
                continue
            quoted = ",".join(f'"{name}"' for name in columns)
            sql = f'INSERT OR IGNORE INTO "{table}" ({quoted}) VALUES ({",".join("?" for _ in columns)})'
            for row in source.execute(f'SELECT {quoted} FROM "{table}"'):
                target.execute(sql, row)
                count += 1

        for table, id_column in main.pg_database._AUTO_IDS.items():
            target.execute(
                f"SELECT setval(pg_get_serial_sequence('\"{table}\"', '{id_column}'), "
                f"GREATEST(COALESCE(MAX(\"{id_column}\"), 1), 1), COUNT(*) > 0) FROM \"{table}\""
            )
        target.commit()
    finally:
        source.close()
        target.close()
    print(f"Copied {count} rows into PostgreSQL.")


if __name__ == "__main__":
    migrate()
